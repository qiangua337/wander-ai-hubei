import { meal, ride, visit, walk, type DayJourney } from './day-journeys';
import type { DayKind } from './practical';
import type { RouteEffort } from './route-details';
import { day, type CityGuide, type TripDay } from './types';

type AttractionInput = DayJourney & {
  title: string;
  region: string;
  effort: RouteEffort;
  kind: DayKind;
  breakfast: string;
  transport: string;
  featuredVisit?: 'afternoon';
  afternoon: NonNullable<DayJourney['afternoon']>;
  lodgingNote: string;
  note: string;
};

function attractionRoute(placeId: string, input: AttractionInput) {
  const { title, region, effort, kind, breakfast, transport, featuredVisit, ...journey } = input;
  const { morning, afternoon, lunch, night, dinner, lodgingNote, note } = journey;
  return {
    placeId, kind, journey,
    visitTitle: (featuredVisit === 'afternoon' ? afternoon : morning).place,
    detail: { region, effort, breakfast, lunch: `${lunch.area}：${lunch.food}`, dinner: `${night}：${dinner}` },
    day: day(title, [morning.place, morning.note ?? '按景区当日指引安排游览。'], [afternoon.place, afternoon.note ?? '按实际余量游览。'],
      ['就近晚餐与住宿', `${dinner} ${lodgingNote}`], transport, `午餐在${lunch.area}。${lunch.food} 晚餐：${dinner}`, note),
  };
}

type AttractionRoute = ReturnType<typeof attractionRoute>;

